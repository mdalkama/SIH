// Function to get news by ID
export const getNewsById = (id) => {
  return newsData.find(news => news.id === parseInt(id))
}

// Function to get all news
export const getAllNews = () => {
  return newsData
}

// Function to get news by category
export const getNewsByCategory = (category) => {
  return newsData.filter(news => news.category === category)
}

// Function to get recent news (last n items)
export const getRecentNews = (count = 6) => {
  return newsData.slice(0, count)
}
